object PdfAndExportManager {

    private fun exportsDir(context: Context): File {
        val dir = File(context.cacheDir, "exports")
        if (!dir.exists()) dir.mkdirs()
        return dir
    }

    fun generateReceiptPdf(
        context: Context,
        receipt: Receipt,
        language: AppLanguage
    ): File {
        val doc = PdfDocument()
        val pageInfo = PdfDocument.PageInfo.Builder(595, 842, 1).create()
        val page = doc.startPage(pageInfo)
        val canvas: Canvas = page.canvas

        val headerBgPaint = Paint().apply { color = Color.parseColor("#066344") }
        val whiteTitlePaint = Paint().apply {
            color = Color.WHITE
            textSize = 22f
            isFakeBoldText = true
            isAntiAlias = true
        }
        val whiteSubPaint = Paint().apply {
            color = Color.parseColor("#D4F4E6")
            textSize = 12f
            isAntiAlias = true
        }
        val sectionTitlePaint = Paint().apply {
            color = Color.parseColor("#066344")
            textSize = 15f
            isFakeBoldText = true
            isAntiAlias = true
        }
        val labelPaint = Paint().apply {
            color = Color.parseColor("#475569")
            textSize = 13f
            isAntiAlias = true
        }
        val valuePaint = Paint().apply {
            color = Color.parseColor("#0F172A")
            textSize = 13f
            isFakeBoldText = true
            isAntiAlias = true
        }
        val linePaint = Paint().apply {
            color = Color.parseColor("#CBD5E1")
            strokeWidth = 1f
        }
        val badgeBgPaint = Paint().apply {
            color = Color.parseColor("#E4F6EC")
        }
        val badgeTextPaint = Paint().apply {
            color = Color.parseColor("#066344")
            textSize = 14f
            isFakeBoldText = true
            isAntiAlias = true
        }

        // Top Emerald Header
        canvas.drawRect(0f, 0f, 595f, 118f, headerBgPaint)
        canvas.drawText("SMART RENT MANAGER", 40f, 52f, whiteTitlePaint)
        canvas.drawText(
            if (language == AppLanguage.BN) "ডিজিটাল ভাড়া পরিশোধ রসিদ / Official Payment Receipt"
            else "Official Digital Rent Payment Receipt",
            40f,
            78f,
            whiteSubPaint
        )
        canvas.drawText("Receipt #: ${receipt.receiptNumber}", 40f, 98f, whiteSubPaint)

        var y = 160f
        canvas.drawText("Payment & Property Details", 40f, y, sectionTitlePaint)
        y += 14f
        canvas.drawLine(40f, y, 555f, y, linePaint)
        y += 28f

        val rows = listOf(
            "Building Name" to receipt.buildingName,
            "Flat Number" to receipt.flatNumber,
            "Tenant Name" to receipt.tenantName,
            "Payment Date (DD-MM-YYYY)" to receipt.paymentDate,
            "Payment Method" to receipt.paymentMethod.uppercase(),
            "Transaction ID" to receipt.transactionId,
            "Previous Due" to "BDT ${String.format("%,.0f", receipt.previousDue)}",
            "Amount Paid" to "BDT ${String.format("%,.0f", receipt.amountPaid)}",
            "Remaining Due" to "BDT ${String.format("%,.0f", receipt.remainingDue)}",
            "Payment Status" to receipt.status.uppercase()
        )

        for ((label, value) in rows) {
            canvas.drawText(label, 40f, y, labelPaint)
            canvas.drawText(value, 310f, y, valuePaint)
            y += 28f
            canvas.drawLine(40f, y - 10f, 555f, y - 10f, linePaint)
        }

        y += 24f
        canvas.drawRoundRect(40f, y, 555f, y + 54f, 10f, 10f, badgeBgPaint)
        canvas.drawText(
            "VERIFIED PAYMENT - BDT ${String.format("%,.0f", receipt.amountPaid)} (${receipt.status.uppercase()})",
            64f,
            y + 33f,
            badgeTextPaint
        )

        y += 96f
        canvas.drawText(
            "Generated by Smart Rent Manager | Timezone: Asia/Dhaka | ${FormatUtils.todayDdMmYyyy()}",
            40f,
            y,
            labelPaint
        )

        doc.finishPage(page)

        val file = File(exportsDir(context), "receipt_${FormatUtils.sanitizeId(receipt.receiptNumber)}.pdf")
        FileOutputStream(file).use { out ->
            doc.writeTo(out)
        }
        doc.close()
        return file
    }

    fun generateFinancialReportPdf(
        context: Context,
        title: String,
        buildings: List<Building>,
        flats: List<Flat>,
        bills: List<MonthlyBill>,
        payments: List<PaymentRecord>,
        expenses: List<Expense>,
        bankTransactions: List<BankTransaction>,
        cashTransactions: List<CashTransaction>
    ): File {
        val doc = PdfDocument()
        val pageInfo = PdfDocument.PageInfo.Builder(595, 842, 1).create()
        val page = doc.startPage(pageInfo)
        val canvas = page.canvas

        val headerPaint = Paint().apply { color = Color.parseColor("#066344") }
        val titlePaint = Paint().apply {
            color = Color.WHITE
            textSize = 20f
            isFakeBoldText = true
            isAntiAlias = true
        }
        val subPaint = Paint().apply {
            color = Color.parseColor("#D4F4E6")
            textSize = 12f
            isAntiAlias = true
        }
        val sectionPaint = Paint().apply {
            color = Color.parseColor("#066344")
            textSize = 14f
            isFakeBoldText = true
            isAntiAlias = true
        }
        val bodyPaint = Paint().apply {
            color = Color.parseColor("#1E293B")
            textSize = 11.5f
            isAntiAlias = true
        }
        val boldBodyPaint = Paint().apply {
            color = Color.parseColor("#0F172A")
            textSize = 11.5f
            isFakeBoldText = true
            isAntiAlias = true
        }

        canvas.drawRect(0f, 0f, 595f, 96f, headerPaint)
        canvas.drawText("SMART RENT MANAGER - FINANCIAL REPORT", 36f, 44f, titlePaint)
        canvas.drawText("$title | Date: ${FormatUtils.todayDdMmYyyy()} (Asia/Dhaka)", 36f, 70f, subPaint)

        var y = 128f
        val totalRent = flats.sumOf { it.monthlyRent }
        val totalBilled = bills.sumOf { it.totalBill }
        val totalCollected = payments.filter { it.verificationStatus == "verified" }.sumOf { it.amount }
        val totalDue = bills.sumOf { it.remainingDue }
        val totalExpenses = expenses.sumOf { it.amount }
        val netIncome = totalCollected - totalExpenses

        canvas.drawText("Executive Summary (BDT)", 36f, y, sectionPaint)
        y += 22f
        val summaryLines = listOf(
            "Total Buildings: ${buildings.size} | Total Flats: ${flats.size} (Occupied: ${flats.count { it.isOccupied }})",
            "Monthly Base Rent Roll: BDT ${String.format("%,.0f", totalRent)}",
            "Total Billed: BDT ${String.format("%,.0f", totalBilled)} | Verified Collected: BDT ${String.format("%,.0f", totalCollected)}",
            "Outstanding Dues: BDT ${String.format("%,.0f", totalDue)} | Total Expenses: BDT ${String.format("%,.0f", totalExpenses)}",
            "Net Cashflow (Collected - Expenses): BDT ${String.format("%,.0f", netIncome)}"
        )
        for (line in summaryLines) {
            canvas.drawText(line, 36f, y, bodyPaint)
            y += 18f
        }

        y += 16f
        canvas.drawText("Building-wise Collection & Dues", 36f, y, sectionPaint)
        y += 20f
        for (b in buildings.take(8)) {
            val bBills = bills.filter { it.buildingId == b.id }
            val bCollected = bBills.sumOf { it.amountPaid }
            val bDue = bBills.sumOf { it.remainingDue }
            canvas.drawText(
                "${b.name}: Collected BDT ${String.format("%,.0f", bCollected)} | Due BDT ${String.format("%,.0f", bDue)}",
                36f,
                y,
                bodyPaint
            )
            y += 18f
        }

        y += 16f
        canvas.drawText("Recent Verified Payments & Ledger", 36f, y, sectionPaint)
        y += 20f
        for (p in payments.filter { it.verificationStatus == "verified" }.take(12)) {
            if (y > 790f) break
            canvas.drawText(
                "${p.paymentDate} | ${p.buildingName} (${p.flatNumber}) - ${p.tenantName} | ${p.method.uppercase()} | BDT ${String.format("%,.0f", p.amount)}",
                36f,
                y,
                bodyPaint
            )
            y += 16f
        }

        y += 14f
        if (y < 800f) {
            canvas.drawText(
                "Bank Tx Count: ${bankTransactions.size} | Cash Tx Count: ${cashTransactions.size}",
                36f,
                y,
                boldBodyPaint
            )
        }

        doc.finishPage(page)
        val file = File(exportsDir(context), "smart_rent_report_${System.currentTimeMillis()}.pdf")
        FileOutputStream(file).use { doc.writeTo(it) }
        doc.close()
        return file
    }

    fun generateExcelCsvReport(
        context: Context,
        buildings: List<Building>,
        flats: List<Flat>,
        bills: List<MonthlyBill>,
        payments: List<PaymentRecord>,
        expenses: List<Expense>
    ): File {
        val sb = StringBuilder()
        // UTF-8 BOM so Microsoft Excel renders Bangla characters cleanly
        sb.append('\uFEFF')
        sb.appendLine("SMART RENT MANAGER - FINANCIAL EXPORT,${FormatUtils.todayDdMmYyyy()}")
        sb.appendLine()
        sb.appendLine("SECTION 1: BUILDING-WISE SUMMARY")
        sb.appendLine("Building,Address,Floors,Flats,Total Billed (BDT),Collected (BDT),Outstanding Due (BDT)")
        for (b in buildings) {
            val bBills = bills.filter { it.buildingId == b.id }
            sb.appendLine(
                "\"${b.name}\",\"${b.address}\",${b.floorsCount},${b.totalFlats},${bBills.sumOf { it.totalBill }},${bBills.sumOf { it.amountPaid }},${bBills.sumOf { it.remainingDue }}"
            )
        }
        sb.appendLine()
        sb.appendLine("SECTION 2: FLAT-WISE BILLING")
        sb.appendLine("Building,Flat,Floor,Tenant,Phone,Rent,Service,Electricity,Water,Gas,Other,Total Bill,Paid,Due,Status")
        for (f in flats) {
            sb.appendLine(
                "\"${f.buildingName}\",\"${f.flatNumber}\",${f.floorNumber},\"${f.tenantName}\",\"${f.tenantPhone}\",${f.monthlyRent},${f.serviceCharge},${f.electricityBill},${f.waterBill},${f.gasBill},${f.otherCharges},${f.totalMonthlyBill},${f.amountPaid},${f.remainingDue},${f.paymentStatus}"
            )
        }
        sb.appendLine()
        sb.appendLine("SECTION 3: PAYMENTS")
        sb.appendLine("Date,Building,Flat,Tenant,Method,Transaction ID,Amount (BDT),Verification Status")
        for (p in payments) {
            sb.appendLine(
                "${p.paymentDate},\"${p.buildingName}\",\"${p.flatNumber}\",\"${p.tenantName}\",${p.method},\"${p.transactionId}\",${p.amount},${p.verificationStatus}"
            )
        }
        sb.appendLine()
        sb.appendLine("SECTION 4: EXPENSES")
        sb.appendLine("Date,Building,Category,Source,Amount (BDT),Description")
        for (e in expenses) {
            sb.appendLine(
                "${e.date},\"${e.buildingName}\",\"${e.category}\",${e.paymentSource},${e.amount},\"${e.description}\""
            )
        }

        val file = File(exportsDir(context), "smart_rent_financial_${System.currentTimeMillis()}.csv")
        file.writeText(sb.toString(), Charsets.UTF_8)
        return file
    }

    fun generateBackupJsonFile(context: Context, jsonContent: String): File {
        val file = File(exportsDir(context), "smart_rent_backup_${FormatUtils.todayDdMmYyyy()}.json")
        file.writeText(jsonContent, Charsets.UTF_8)
        return file
    }

    fun shareOrOpenFile(context: Context, file: File, mimeType: String, chooserTitle: String) {
        val uri = FileProvider.getUriForFile(
            context,
            "${context.packageName}.fileprovider",
            file
        )
        val shareIntent = Intent(Intent.ACTION_SEND).apply {
            type = mimeType
            putExtra(Intent.EXTRA_STREAM, uri)
            addFlags(Intent.FLAG_GRANT_READ_URI_PERMISSION)
        }
        context.startActivity(Intent.createChooser(shareIntent, chooserTitle))
    }
}
